/**
 * Generates public/robots.txt and public/sitemap.xml from a single source
 * of truth (the site URL + the real route list), so neither file can drift
 * out of sync with the actual domain or the actual routes.
 *
 * Runs automatically before every `npm run build` (see package.json's
 * "prebuild" script — npm runs it for you, no need to call this directly).
 *
 * Reads the domain from the VITE_SITE_URL environment variable — the same
 * variable src/lib/siteConfig.js reads at runtime via import.meta.env.
 * Plain Node scripts don't get Vite's automatic .env loading, so set this
 * as a real environment variable in your deployment platform (Netlify,
 * Vercel, Cloudflare Pages, etc. all support this in project settings) or
 * export it in your shell before building. Falls back to the same
 * placeholder domain siteConfig.js uses when unset, so local builds still
 * work — but that placeholder must not go to production. See
 * siteConfig.js for the full explanation.
 */
import fs from 'node:fs'
import path from 'node:path'
import { seoByPath } from '../src/data/seo.js'

const PLACEHOLDER_SITE_URL = 'https://www.zanokuhleacademy.org.za'
const siteUrl = (process.env.VITE_SITE_URL || PLACEHOLDER_SITE_URL).replace(/\/$/, '')
const isPlaceholder = siteUrl === PLACEHOLDER_SITE_URL

if (isPlaceholder) {
  console.warn(
    '\n⚠️  generate-seo-files: VITE_SITE_URL is not set — robots.txt and sitemap.xml are being generated ' +
      'against the placeholder domain (' +
      PLACEHOLDER_SITE_URL +
      '). Set VITE_SITE_URL to the real domain before a production deploy.\n',
  )
}

// changefreq/priority per route — matches the hand-tuned values from the
// original SEO pass (home = highest priority/most frequent, contact/get-
// involved = high priority since they're conversion pages, etc).
const routeMeta = {
  '/': { changefreq: 'weekly', priority: '1.0' },
  '/about': { changefreq: 'monthly', priority: '0.8' },
  '/programmes': { changefreq: 'monthly', priority: '0.9' },
  '/programmes/alexandra-learner-advancement': { changefreq: 'monthly', priority: '0.8' },
  '/programmes/early-childhood-development': { changefreq: 'monthly', priority: '0.8' },
  '/programmes/education-after-school': { changefreq: 'monthly', priority: '0.8' },
  '/programmes/skills-and-youth-development': { changefreq: 'monthly', priority: '0.8' },
  '/programmes/social-and-community-development': { changefreq: 'monthly', priority: '0.8' },
  '/get-involved': { changefreq: 'monthly', priority: '0.9' },
  '/impact': { changefreq: 'monthly', priority: '0.7' },
  '/news': { changefreq: 'weekly', priority: '0.6' },
  '/contact': { changefreq: 'yearly', priority: '0.9' },
  '/privacy-policy': { changefreq: 'yearly', priority: '0.3' },
  '/safeguarding': { changefreq: 'yearly', priority: '0.4' },
  '/terms-of-use': { changefreq: 'yearly', priority: '0.3' },
}

const lastmod = new Date().toISOString().slice(0, 10)
const routes = Object.keys(seoByPath)

const missingMeta = routes.filter((r) => !routeMeta[r])
if (missingMeta.length > 0) {
  console.error('generate-seo-files: no sitemap changefreq/priority configured for route(s):', missingMeta)
  process.exit(1)
}

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<!--
  Zanokuhle Intellectuals Academy — generated by scripts/generate-seo-files.mjs
  from src/data/seo.js's route list. Do not hand-edit — edit routeMeta in
  that script (or add a route to src/data/seo.js) and rebuild instead.
-->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${routes
  .map(
    (route) => `  <url>
    <loc>${siteUrl}${route}</loc>
    <lastmod>${lastmod}</lastmod>
    <changefreq>${routeMeta[route].changefreq}</changefreq>
    <priority>${routeMeta[route].priority}</priority>
  </url>`,
  )
  .join('\n')}
</urlset>
`

const robots = `# Zanokuhle Intellectuals Academy — the entire public site is indexable;
# there are no admin, test or duplicate-content paths to block.
# Generated by scripts/generate-seo-files.mjs — do not hand-edit.
User-agent: *
Allow: /

Sitemap: ${siteUrl}/sitemap.xml
`

const publicDir = path.join(process.cwd(), 'public')
fs.writeFileSync(path.join(publicDir, 'sitemap.xml'), sitemap)
fs.writeFileSync(path.join(publicDir, 'robots.txt'), robots)
console.log(`generate-seo-files: wrote sitemap.xml + robots.txt for ${siteUrl} (${routes.length} routes)`)
